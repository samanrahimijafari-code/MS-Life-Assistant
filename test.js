let fail = 0;
for (const [t, exp, lv] of T) {
  const m = E.match(t), top = m[0];
  const ok = exp === 'NONE' ? !top : top && top.name.includes(exp) && top.lv >= lv;
  if (!ok) { fail++; console.log('✗', t, '→', top ? top.name + ' (lv' + top.lv + ')' : 'NONE', '| انتظار:', exp, lv || ''); }
}
// آزمون منطق سؤال‌ها: «بله» هرگز سطح را پایین نمی‌آورد و سؤال اورژانسی سطح ۳ می‌دهد
const num = E.match('بی حسی دارم')[0];
const chk = (c, m) => { if (!c) { fail++; console.log('✗', m); } };
chk(E.level(num, []) === 2, 'سطح پایه بی‌حسی');
chk(E.level(num, [true]) === 3, 'بی‌حسی ناگهانی یک‌طرفه باید اورژانس شود');
chk(E.level(num, [false, false]) === 2, 'پاسخ خیر نباید سطح را کم کند');
const fat = E.match('خستگی دارم')[0];
chk(E.level(fat, [false, false, false, false]) === 1, 'خستگی ساده سطح ۱');
chk(E.level(fat, [false, true]) === 2, 'خستگی با ۲۴ ساعت به بالا → ۲');
chk(E.level(fat, [false, false, false, true]) === 3, 'خستگی با علائم سکته → ۳');
chk(E.KB.every(e => e.qs.length <= 5), 'تعداد سؤال‌ها حداکثر ۵');
